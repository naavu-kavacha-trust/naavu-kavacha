// Writes public/sitemap.xml (and a "Sitemap:" line in public/robots.txt) for the site's pages, but only once
// SITE_URL is set in src/data/siteConfig.ts. Plain Node, no dependencies. Runs automatically before `npm run build`
// and on its own with `npm run sitemap`.
import { existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const GENERATED_MARK = "<!-- generated by scripts/sitemap.mjs: edit SITE_URL in src/data/siteConfig.ts, not this file -->";

/** Reads SITE_URL and the page paths out of siteConfig.ts (a test checks this against the real values). */
export function parseSiteConfig(text) {
  const url = /export const SITE_URL\s*(?::\s*string)?\s*=\s*"([^"]*)"/.exec(text)?.[1] ?? "";
  const block = /export const ROUTES\s*=\s*\{([\s\S]*?)\}\s*as const/.exec(text)?.[1] ?? "";
  const routes = [...block.matchAll(/:\s*"(\/[^"]*)"/g)].map((m) => m[1]);
  return { siteUrl: url.trim().replace(/\/+$/, ""), routes };
}

/** Only a full web address counts; anything else is treated as "not set yet". */
export const isUsableSiteUrl = (siteUrl) => /^https?:\/\/[^\s/]+/i.test(siteUrl);

const escapeXml = (text) =>
  text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");

export function buildSitemap(siteUrl, routes) {
  const urls = routes.map((route) => `  <url><loc>${escapeXml(`${siteUrl}${route}`)}</loc></url>`).join("\n");
  return `<?xml version="1.0" encoding="UTF-8"?>\n${GENERATED_MARK}\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`;
}

/** robots.txt with exactly one Sitemap line, replacing any earlier one. */
export function updateRobots(text, siteUrl) {
  const kept = text.split(/\r?\n/).filter((line) => !/^\s*sitemap\s*:/i.test(line));
  while (kept.length && kept[kept.length - 1].trim() === "") kept.pop();
  return `${kept.join("\n")}\n\nSitemap: ${siteUrl}/sitemap.xml\n`;
}

export function run(root = resolve(fileURLToPath(import.meta.url), "..", "..")) {
  const config = parseSiteConfig(readFileSync(resolve(root, "src/data/siteConfig.ts"), "utf8"));
  const sitemapPath = resolve(root, "public/sitemap.xml");
  const robotsPath = resolve(root, "public/robots.txt");

  if (!isUsableSiteUrl(config.siteUrl)) {
    // Not set (or not a full address): make nothing. A leftover file from an earlier run is removed, but a
    // hand-written sitemap (one without our mark) is never touched.
    if (existsSync(sitemapPath) && readFileSync(sitemapPath, "utf8").includes(GENERATED_MARK)) rmSync(sitemapPath);
    console.log("sitemap: SITE_URL is not set in src/data/siteConfig.ts, so no sitemap was written.");
    return { written: false };
  }

  writeFileSync(sitemapPath, buildSitemap(config.siteUrl, config.routes));
  if (existsSync(robotsPath)) writeFileSync(robotsPath, updateRobots(readFileSync(robotsPath, "utf8"), config.siteUrl));
  console.log(`sitemap: wrote public/sitemap.xml with ${config.routes.length} pages for ${config.siteUrl}`);
  return { written: true };
}

// Run when called from the command line, not when imported (the tests import it).
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) run();
